// Basics 1.5: build output and a local .env show up as untracked; ignore them with a committed .gitignore.
import { commitsOf, headCommit, ignoreMatcher, isWorkingTreeClean, repo } from '../../git'
import type { GitState } from '../../git'
import type { GitScenario } from './types'

/** The generated and local files the .gitignore has to cover. */
const KEPT_OUT = ['dist/app.js', 'dist/app.css', '.env']

const setup = () => repo()
  .file('README.md', [
    '# Corner Bakery shop',
    '',
    'Run `npm run build` to bundle src/ into dist/; the server only ever gets dist/.',
    '',
    'Local settings: copy .env.example to .env and put your own test keys in it. Never commit .env.'
  ].join('\n'))
  .file('package.json', '{\n  "name": "bakery-shop",\n  "private": true,\n  "scripts": {\n    "build": "node build.js"\n  }\n}')
  .file('build.js', '// Bundles src/ into dist/. The output is generated: change src/, never dist/.\nimport { bundle } from \'./tools/bundle.js\'\n\nbundle(\'src\', \'dist\')')
  .file('src/app.js', '// Entry point of the shop: renders the product list and the cart.\nimport { renderShop } from \'./shop.js\'\n\nrenderShop(document.querySelector(\'#shop\'))')
  .file('.env.example', '# Copy to .env and fill in your own values.\nPAYMENT_API_KEY=your-test-key\nDEBUG=false')
  .commit('Set up the shop build', { author: 'Maya' })
  .file('dist/app.js', '/* generated by build.js, do not edit */\n(()=>{renderShop(document.querySelector("#shop"))})();')
  .file('dist/app.css', '/* generated by build.js, do not edit */\nbody{font-family:Georgia,serif}')
  .file('.env', '# Your local settings. Never commit this file.\nPAYMENT_API_KEY=test-key-not-real-0000\nDEBUG=true')
  .build()

/** The .gitignore of the newest commit, as a matcher; null when there is none. */
function committedIgnore(state: GitState) {
  const text = headCommit(state)?.tree['.gitignore']
  return text === undefined ? null : ignoreMatcher({ '.gitignore': text })
}

export const ignoreBuildFiles: GitScenario = {
  id: 'git-10-ignore-build-files',
  track: 'git',
  kind: 'scenario',
  difficulty: 2,
  minutes: 6,
  title: 'Ignore build files',
  story: [
    'You ran the build of the bakery shop for the first time. Now `git status` lists a `dist/` folder full of generated files, and `.env` with your local payment key. The key is a test value, but real keys must never end up in the history.',
    'Tell git to ignore both: write a `.gitignore` with one line for `dist/` and one for `.env`, commit it, and leave the working tree clean. The files themselves stay on your disk.'
  ].join('\n\n'),
  setup,
  goals: [
    {
      id: 'gitignore',
      label: 'A committed .gitignore ignores dist/ and .env',
      check: ({ state }) => {
        const ignored = committedIgnore(state)
        return !!ignored && KEPT_OUT.every(ignored) && !ignored('src/app.js')
      }
    },
    { id: 'kept', label: 'dist/ and .env are still on your disk', check: ({ state }) => KEPT_OUT.every(path => state.workdir[path] !== undefined) },
    {
      id: 'not-committed',
      label: 'Neither dist/ nor .env is in any commit',
      check: ({ state }) => commitsOf(state, 'HEAD').every(commit => KEPT_OUT.every(path => commit.tree[path] === undefined))
    },
    { id: 'clean', label: 'Working tree clean: git status shows nothing to commit', check: ({ state }) => isWorkingTreeClean(state) }
  ],
  hints: [
    'git leaves alone whatever a `.gitignore` file names, one pattern per line. `dist/` stands for the whole folder.',
    '`echo "dist/" > .gitignore` creates the file with its first line, `echo ".env" >> .gitignore` adds a second one. After that, `git status` lists only the `.gitignore` itself: commit it like any other file.',
    'Run `echo "dist/" > .gitignore`, `echo ".env" >> .gitignore`, `git add .gitignore`, then `git commit -m "Ignore build output and local settings"`.'
  ],
  debrief: {
    title: 'Some files never belong in git',
    paragraphs: [
      'Build output can be made again from the source at any time; committing it only fills the history with noise and conflicts. Local settings like `.env` differ per person and often hold secrets. A `.gitignore` keeps both out of `git status` and out of `git add .`.',
      'The `.gitignore` itself is committed, so everyone on the team ignores the same files. `dist/` names a folder, `*.log` every file ending in .log, `/build` only the build folder at the top, and `!keep.log` makes an exception.',
      'Ignoring only works for files git does not track yet. A file that is already committed stays tracked even when a pattern matches it, so put the `.gitignore` in place before the first `git add .`.'
    ]
  },
  solution: [
    'echo "dist/" > .gitignore',
    'echo ".env" >> .gitignore',
    'git status',
    'git add .gitignore',
    'git commit -m "Ignore build output and local settings"'
  ]
}

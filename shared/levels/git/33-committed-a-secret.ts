// Disasters 7.4: `git add .` took .env (the payment key) into your last commit; not pushed. Untrack it with
// `git rm --cached`, ignore it, and amend, so no commit on main ever held the key. A new commit that deletes .env
// leaves the key in the history; plain `git rm` deletes your local file. The debrief covers the pushed case: rotate.
import { commitsOf, headCommit, ignoreMatcher, isIgnored, isWorkingTreeClean } from '../../git'
import type { GitState } from '../../git'
import type { GitScenario } from './types'
import { bakerySite, text } from './bakery'

const ENV = text('# Your local settings for the shop. Never commit this file.', 'PAYMENT_API_KEY=test-key-not-real-0000')
const PAYMENT = text(
  '// Card payments for cake orders. The key comes from .env, never from the code.',
  'import { createClient } from \'./payment-client.js\'',
  '',
  'export const payments = createClient(process.env.PAYMENT_API_KEY)'
)
const CLIENT = text(
  '// A thin wrapper around the payment provider\'s API. Jonas: sandbox until Maya signs the contract.',
  'export const createClient = key => ({ key, sandbox: true })'
)

const setup = () => bakerySite()
  .file('.gitignore', '# Generated by the build. (Jonas)\ndist/')
  .commit('Ignore the build output', { author: 'Jonas' })
  .origin()
  .file('src/payment.js', PAYMENT)
  .file('src/payment-client.js', CLIENT)
  .file('.env', ENV)
  // the builder's commit stages everything, like the `git add .` in the story
  .commit('Add card payments for cake orders')
  .build()

/** The newest commit's .gitignore ignores .env (and still dist/). */
function committedIgnoreCoversEnv(state: GitState): boolean {
  const ignore = headCommit(state)?.tree['.gitignore']
  if (ignore === undefined) return false
  const ignored = ignoreMatcher({ '.gitignore': ignore })
  return ignored('.env') && ignored('dist/app.js')
}

export const committedASecret: GitScenario = {
  id: 'git-33-committed-a-secret',
  track: 'git',
  kind: 'scenario',
  difficulty: 2,
  minutes: 6,
  title: 'Committed a secret',
  story: [
    'You just committed "Add card payments for cake orders" with `git add .`, and only then saw what it took along: `.env`, with the shop\'s payment key in it. The commit isn\'t pushed, so the key hasn\'t left your machine yet.',
    'Take `.env` out of git without deleting it from your disk, add a line for it to `.gitignore` so it can\'t sneak back in, and rewrite the last commit so it holds your payment code and the new .gitignore, but no key.'
  ].join('\n\n'),
  setup,
  goals: [
    {
      id: 'out-of-history',
      label: '`.env` is in no commit on main',
      check: ({ state }) => commitsOf(state, 'main').every(commit => commit.tree['.env'] === undefined)
    },
    {
      id: 'one-commit',
      label: 'One commit on top of origin/main, with your payment code and a .gitignore that ignores .env',
      check: ({ state }) => commitsOf(state, 'origin/main..main').length === 1 && headCommit(state)?.tree['src/payment.js'] === PAYMENT
        && committedIgnoreCoversEnv(state)
    },
    {
      id: 'kept',
      label: '`.env` is still on your disk, ignored, and nothing is left to commit',
      check: ({ state }) => state.workdir['.env'] === ENV && isIgnored(state, '.env') && isWorkingTreeClean(state)
    }
  ],
  hints: [
    '`git rm --cached <file>` stops tracking a file but leaves it on your disk. Without `--cached`, git deletes the file too.',
    'A new commit that removes .env would still leave the key in the commit before it. Rewrite the last commit instead: untrack .env, add it to .gitignore, stage the .gitignore, then `git commit --amend`.',
    '`git rm --cached .env`, `echo ".env" >> .gitignore`, `git add .gitignore`, then `git commit --amend --no-edit`.'
  ],
  debrief: {
    title: 'Untrack it, ignore it, rewrite the commit',
    paragraphs: [
      '`git rm --cached .env` took the file out of the staging area, so the next commit leaves it out, and kept it on your disk, where your local setup needs it. The line in `.gitignore` makes `git add .` skip it from now on. `git commit --amend` then replaced your commit with one that never held the key.',
      'Why not a new commit "Remove .env"? The key would still be in the commit before it, and anyone with the history could read it. Amending worked because the bad commit was the last one and nobody had it yet.',
      'Had you pushed it, rewriting the history would not be enough: teammates may have fetched it, and hosting services keep old commits around. Treat a pushed key as leaked: rotate it (create a new key, switch the old one off), then clean up.',
      'The habit that prevents all of this: look at `git status` before `git add .`, and put `.env` into the `.gitignore` the day a project starts.'
    ]
  },
  solution: [
    'git status',
    'git rm --cached .env',
    'echo ".env" >> .gitignore',
    'git add .gitignore',
    'git commit --amend --no-edit'
  ]
}
